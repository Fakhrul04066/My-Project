void solve()
{
    int n;
    cin>>n;
   int ans=0;
   while(n>0){
    if(n%2==1){
        ans++;
    }
    n/=2;
   }
   cout<<ans<<endl;
}

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    while (t--)
        solve();

    return 0;
}